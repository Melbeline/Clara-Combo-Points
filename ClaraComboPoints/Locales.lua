local english = strings.enUS
local client = GetLocale and GetLocale()
ns.lang = strings[client] and client or "enUS"

function ns:IsLanguage(code)
  return strings[code] ~= nil
end

-- L.KEY always reads the current language, so switching language only needs a relabel.
ns.L = setmetatable({}, {
  __index = function(_, key)
    local text = strings[ns.lang][key]
    if text == nil then text = english[key] end
    return text
  end,
})
