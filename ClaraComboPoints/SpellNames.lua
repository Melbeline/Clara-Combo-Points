-- German, to find a spell by its name in any of these languages (class spells panel, Add a
-- spell) and to show the panel in the addon's language. The game's own name (in the client's
-- language) is always searched too. A name in parentheses after the spell's name says where
-- the aura comes from (a talent, an effect); it is not part of the name in the game. Names past
-- the third are old names of the spell, still found by a search.

local _, ns = ...

-- Search key: lower case, accents off (é è ê ë all e, ß ss, œ oe), apostrophes off, any other
-- punctuation and spacing one space. "Mot de pouvoir : Robustesse" -> "mot de pouvoir robustesse".
local ACCENTS = {}
for plain, letters in pairs({ a = "àáâãäåÀÁÂÃÄÅ", c = "çÇ", e = "èéêëÈÉÊË", i = "ìíîïÌÍÎÏ", n = "ñÑ", o = "òóôõöøÒÓÔÕÖØ",
  u = "ùúûüÙÚÛÜ", y = "ýÿÝ", ss = "ß", oe = "œŒ", ae = "æÆ" }) do
  for ch in letters:gmatch("[\192-\223][\128-\191]") do ACCENTS[ch] = plain end
end

function ns:SearchKey(text)
  local key = tostring(text or ""):gsub("\226\128\153", "'"):gsub("'", "")
  key = key:gsub("[\192-\223][\128-\191]", ACCENTS):lower()
  key = key:gsub("[%p%s]+", " ")
  return (key:gsub("^ ", ""):gsub(" $", ""))
end

